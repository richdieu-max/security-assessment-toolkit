"""Check the KQL alert library and build its index.

Every .kql file in logging/kql must start with a header of '// key: value' lines.
This script checks that every required key is present, IDs are unique, severity
is 0-4, the query starts with the table named in the header, and brackets and
quotes balance. It can also write the rule index and an Alert Test Log template
that matches the workbook's 'Logging Validation' sheet columns.

    python tools/check_kql.py                                    # check only
    python tools/check_kql.py --index logging/kql/INDEX.md       # write the index
    python tools/check_kql.py --test-log logging/alert-test-log.template.csv
"""
import argparse
import csv
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
KQL_DIR = ROOT / "logging" / "kql"
REQUIRED = ["id", "title", "severity", "table", "frequency", "window", "threshold", "controls", "attack", "fire-test"]
HEADER = re.compile(r"^//\s*([a-z-]+):\s*(.+?)\s*$")


def parse(path):
    meta, body = {}, []
    in_header = True
    for line in path.read_text(encoding="utf-8").splitlines():
        m = HEADER.match(line) if in_header else None
        if m:
            meta[m.group(1)] = m.group(2)
        else:
            in_header = False
            body.append(line)
    return meta, "\n".join(body).strip()


def strip_strings(q):
    q = re.sub(r'@"[^"]*"', '""', q)
    q = re.sub(r'"(?:\\.|[^"\\])*"', '""', q)
    return re.sub(r"'(?:\\.|[^'\\])*'", "''", q)


def check(path, meta, query):
    errors = []
    for k in REQUIRED:
        if k not in meta:
            errors.append(f"missing header '{k}'")
    if meta.get("severity", "").strip() not in {"0", "1", "2", "3", "4"}:
        errors.append("severity must be 0-4")
    if not re.fullmatch(r"KQL-\d{2}", meta.get("id", "")):
        errors.append("id must look like KQL-01")
    if not re.fullmatch(r"PT\d+[MH]", meta.get("frequency", "")):
        errors.append("frequency must be ISO 8601, e.g. PT5M")
    lines = [l for l in query.splitlines() if l.strip() and not l.strip().startswith("//")]
    first_table = next((l.strip() for l in lines if not l.strip().startswith("let ")), "")
    if first_table.split()[0:1] != [meta.get("table", "")]:
        errors.append(f"query should start with table '{meta.get('table')}', starts with '{first_table[:40]}'")
    bare = strip_strings(query)
    for o, c in ("()", "[]", "{}"):
        if bare.count(o) != bare.count(c):
            errors.append(f"unbalanced {o}{c}")
    if bare.count('"') % 2 or bare.count("'") % 2:
        errors.append("unbalanced quotes")
    if "| where" not in query and "| summarize" not in query:
        errors.append("query has no filter")
    return errors


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--index", type=pathlib.Path)
    ap.add_argument("--test-log", type=pathlib.Path)
    args = ap.parse_args()

    files = sorted(KQL_DIR.glob("*.kql"))
    if not files:
        sys.exit("no .kql files found")
    rules, failed, seen = [], False, {}
    for f in files:
        meta, query = parse(f)
        errs = check(f, meta, query)
        if meta.get("id") in seen:
            errs.append(f"duplicate id (also in {seen[meta['id']]})")
        seen[meta.get("id")] = f.name
        for e in errs:
            print(f"{f.name}: {e}")
        failed |= bool(errs)
        rules.append((meta, f.name))
    if failed:
        sys.exit(1)
    rules.sort(key=lambda r: r[0]["id"])
    print(f"{len(rules)} rules OK")

    if args.index:
        out = ["| ID | Rule | Sev | Table | Every / window | ATT&CK | Controls | File |", "|---|---|---|---|---|---|---|---|"]
        for m, name in rules:
            out.append(f"| {m['id']} | {m['title']} | {m['severity']} | {m['table']} | {m['frequency']} / {m['window']} | {m['attack']} | {m['controls']} | [{name}]({name}) |")
        args.index.write_text("# KQL alert rules\n\nGenerated by `tools/check_kql.py --index`. Do not edit by hand.\n\n" + "\n".join(out) + "\n", encoding="utf-8")
        print(f"wrote {args.index}")
    if args.test_log:
        with args.test_log.open("w", newline="", encoding="utf-8") as fh:
            w = csv.writer(fh)
            w.writerow(["Rule", "Type", "How to fire it safely", "Fired (UTC)", "Tester (role)", "Received?"])
            for m, _ in rules:
                w.writerow([f"{m['id']} {m['title']}", "Log search", m["fire-test"], "", "", ""])
        print(f"wrote {args.test_log}")


if __name__ == "__main__":
    main()
